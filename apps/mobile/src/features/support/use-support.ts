import type { ApiClient } from '@nilzora/api-client';
import type {
  ChatConversationDetail,
  ChatConversationListResponse,
  ChatMessage,
  ChatMessagePage,
  SendChatMessageResponse,
  StartChatConversationRequest,
} from '@nilzora/contracts';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useCallback } from 'react';
import { useSignedInUserId } from '@/auth/session-context';
import { queryKeys } from '@/query/query-keys';
import { useAuthorizedApi } from '@/query/use-authorized-api';
import { appendStoredMessage } from './optimistic-messages';

/*
 * Support chat queries
 * --------------------
 * Everything the app shows about a conversation comes from the API, read with the caller's
 * own access token, so the server decides which threads this account may see. A conversation
 * is only ever named by its id; the account is never sent from the app.
 */

export function useSupportConversations() {
  const run = useAuthorizedApi();
  const userId = useSignedInUserId();
  return useQuery({
    queryKey: queryKeys.support.conversations(userId),
    queryFn: ({ signal }) =>
      run<ChatConversationListResponse>((api, token) =>
        api.listChatConversations(token, { pageSize: 30 }, { signal }),
      ),
    enabled: userId !== null,
  });
}

export function useSupportConversation(conversationId: string | null) {
  const run = useAuthorizedApi();
  const userId = useSignedInUserId();
  return useQuery({
    queryKey: queryKeys.support.conversation(userId, conversationId ?? 'none'),
    queryFn: ({ signal }) =>
      run<ChatConversationDetail>((api, token) =>
        api.getChatConversation(token, conversationId ?? '', { signal }),
      ),
    enabled: userId !== null && conversationId !== null,
  });
}

export function useSupportMessages(conversationId: string | null) {
  const run = useAuthorizedApi();
  const userId = useSignedInUserId();
  return useQuery({
    queryKey: queryKeys.support.messages(userId, conversationId ?? 'none'),
    queryFn: ({ signal }) =>
      run<ChatMessagePage>((api, token) =>
        api.listChatMessages(token, conversationId ?? '', { limit: 40 }, { signal }),
      ),
    enabled: userId !== null && conversationId !== null,
  });
}

/**
 * One page of messages before a sequence number, for scrolling back. It is a plain read, not a
 * socket message: history is always fetched, never replayed from an event.
 */
export async function fetchOlderSupportMessages(
  api: ApiClient,
  accessToken: string,
  conversationId: string,
  beforeSeq: number,
): Promise<ChatMessage[]> {
  const page = await api.listChatMessages(accessToken, conversationId, {
    before: beforeSeq,
    limit: 40,
  });
  return [...page.messages].reverse();
}

/**
 * Sends a message. `clientMessageId` is generated by the caller and reused on retry, so a
 * connection that drops after the request reached the server cannot produce a duplicate.
 *
 * On success the stored message is merged into the cached page (one write, no refetch); only
 * the conversation list is invalidated, because its preview and ordering really did change.
 */
export function useSendSupportMessage(conversationId: string) {
  const run = useAuthorizedApi();
  const userId = useSignedInUserId();
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: (input: { clientMessageId: string; body: string; replyToId?: string | null }) =>
      run<SendChatMessageResponse>((api, token) =>
        api.sendChatMessage(token, conversationId, input),
      ),
    onSuccess: (result) => {
      queryClient.setQueryData<ChatMessagePage>(
        queryKeys.support.messages(userId, conversationId),
        (page) => appendStoredMessage(page, result.message),
      );
      void queryClient.invalidateQueries({ queryKey: queryKeys.support.conversations(userId) });
    },
  });
}

/** The page-before helper, bound to the caller's own token. */
export function useOlderSupportMessages(): (
  conversationId: string,
  beforeSeq: number,
) => Promise<ChatMessage[]> {
  const run = useAuthorizedApi();
  return useCallback(
    (conversationId: string, beforeSeq: number) =>
      run<ChatMessage[]>((api, token) =>
        fetchOlderSupportMessages(api, token, conversationId, beforeSeq),
      ),
    [run],
  );
}

/** Opens a thread, or continues the customer's live one of the same kind. */
