/**
 * A fresh message id, shaped as the RFC 4122 version 4 UUID the API validates.
 *
 * `crypto.randomUUID` is not on every React Native runtime, so this writes the four fixed
 * bits itself: the version nibble is 4 and the variant nibble is 8, 9, a or b. Without them
 * the string looks like a UUID but is refused by the API's validator, and every send fails.
 */
export function newClientMessageId(): string {
  const hex = '0123456789abcdef';
  let out = '';
  for (let index = 0; index < 32; index += 1) {
    const value =
      index === 12
        ? 4
        : index === 16
          ? 8 + Math.floor(Math.random() * 4)
          : Math.floor(Math.random() * 16);
    out += hex[value];
    if (index === 7 || index === 11 || index === 15 || index === 19) out += '-';
  }
  return out;
}

/**
 * Closes or reopens the customer's own thread. The API refuses any other status to a customer,
 * and a closed thread refuses new messages until it is reopened.
 */
export function useSetSupportStatus(conversationId: string) {
  const run = useAuthorizedApi();
  const userId = useSignedInUserId();
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: (status: 'open' | 'closed') =>
      run<ChatConversationDetail>((api, token) => api.setChatStatus(token, conversationId, status)),
    onSuccess: (detail) => {
      queryClient.setQueryData(queryKeys.support.conversation(userId, conversationId), detail);
      void queryClient.invalidateQueries({
        queryKey: queryKeys.support.messages(userId, conversationId),
      });
      void queryClient.invalidateQueries({ queryKey: queryKeys.support.conversations(userId) });
    },
  });
}

/**
 * The customer's latest orders, so a new conversation can name one. Read only when the composer
 * asks for it; the API still checks the order belongs to this account when the thread starts.
 */
export function useRecentOrdersForSupport(enabled: boolean) {
  const run = useAuthorizedApi();
  const userId = useSignedInUserId();
  return useQuery({
    queryKey: queryKeys.orders.list(userId, { page: 1, pageSize: 5 }),
    queryFn: ({ signal }) =>
      run((api, token) => api.listOrders(token, { page: 1, pageSize: 5 }, { signal })),
    enabled: enabled && userId !== null,
  });
}
