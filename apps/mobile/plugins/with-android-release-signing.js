/* eslint-disable @typescript-eslint/no-require-imports -- Expo config plugins are loaded by Node from a CommonJS package (no "type": "module" in package.json) */
const { withAppBuildGradle } = require('expo/config-plugins');

/*
 * Keeps release builds off the template's debug key.
 *
 * Expo's Android template signs *every* variant, release included, with `debug.keystore` — fine
 * for a debug APK on a test phone, unacceptable for anything that could reach Google Play: the
 * debug key is public, and a package signed with it cannot be re-signed later.
 *
 * This plugin makes release signing explicit and environment-driven:
 *
 *  - a `release` signing config is added that reads a private keystore from
 *    NILZORA_ANDROID_KEYSTORE_PATH / NILZORA_ANDROID_KEYSTORE_PASSWORD /
 *    NILZORA_ANDROID_KEY_ALIAS / NILZORA_ANDROID_KEY_PASSWORD (no keystore, alias or password is
 *    ever committed, and no value is baked into the generated file);
 *  - the release build type uses that config instead of `signingConfigs.debug`;
 *  - any release task stops the build with a clear message when those variables are missing,
 *    so a debug-signed artifact can never be produced by accident.
 *
 * Debug builds are untouched: they keep the template's debug key, so `pnpm android:apk` and
 * `expo run:android` behave exactly as before. Release minification
 * (`android.enableMinifyInReleaseBuilds`) and the reanimated ProGuard keep rules are already part
 * of the SDK 58 template (verified in node_modules/expo/template.tgz), so they need no plugin.
 */

const MARKER = 'nilzora:android-release-signing';

/** Every variable a release build needs; reported by name only, never by value. */
const REQUIRED_VARIABLES = [
  'NILZORA_ANDROID_KEYSTORE_PATH',
  'NILZORA_ANDROID_KEYSTORE_PASSWORD',
  'NILZORA_ANDROID_KEY_ALIAS',
  'NILZORA_ANDROID_KEY_PASSWORD',
];

const SIGNING_CONFIGS_BLOCK = `
    // ${MARKER} - see plugins/with-android-release-signing.js. Generated by Expo prebuild; do not edit.
    //
    // The release key is injected at build time and never committed. With no key configured the
    // config stays empty and the task-graph guard at the end of this file stops a release build,
    // so no artifact is ever signed with the debug key.
    def nilzoraReleaseKeystore = System.getenv('NILZORA_ANDROID_KEYSTORE_PATH')
    signingConfigs {
        release {
            if (nilzoraReleaseKeystore) {
                storeFile file(nilzoraReleaseKeystore)
                storePassword System.getenv('NILZORA_ANDROID_KEYSTORE_PASSWORD')
                keyAlias System.getenv('NILZORA_ANDROID_KEY_ALIAS')
                keyPassword System.getenv('NILZORA_ANDROID_KEY_PASSWORD')
            }
        }
    }
`;

const GUARD_BLOCK = `
// ${MARKER}-guard - see plugins/with-android-release-signing.js. Generated by Expo prebuild.
//
// Release builds must never fall back to the public debug key: missing credentials stop the build
// with the names of the variables to set instead of producing an uploadable debug-signed artifact.
gradle.taskGraph.whenReady { graph ->
    def releaseTasks = ['assembleRelease', 'bundleRelease', 'packageRelease', 'installRelease']
    def wantsRelease = graph.allTasks.any { task -> releaseTasks.contains(task.name) }
    if (wantsRelease) {
        def missing = [${REQUIRED_VARIABLES.map((name) => `'${name}'`).join(', ')}].findAll { name ->
            def value = System.getenv(name)
            value == null || value.trim().isEmpty()
        }
        if (!missing.isEmpty()) {
            throw new GradleException(
                'Release signing is not configured. Set ' + missing.join(', ') +
                ' for the release build; the keystore and its passwords are never committed.'
            )
        }
    }
}
`;

/**
 * Points the release build type at the environment-backed signing config, leaving debug alone.
 * Returns the contents unchanged when the release block cannot be found, so a template change
 * fails loudly at review time rather than producing a silently debug-signed release.
 */
function useReleaseSigning(contents) {
  const buildTypesAt = contents.indexOf('buildTypes {');
  if (buildTypesAt === -1) return contents;
  const releaseAt = contents.indexOf('release {', buildTypesAt);
  if (releaseAt === -1) return contents;
  const debugSigningAt = contents.indexOf('signingConfig signingConfigs.debug', releaseAt);
  if (debugSigningAt === -1) return contents;

  const before = contents.slice(0, debugSigningAt);
  const after = contents.slice(debugSigningAt + 'signingConfig signingConfigs.debug'.length);
  return `${before}signingConfig nilzoraReleaseKeystore ? signingConfigs.release : null${after}`;
}

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (configWithGradle) => {
    if (configWithGradle.modResults.language !== 'groovy') {
      throw new Error(`${MARKER}: android/app/build.gradle is not Groovy; cannot sign releases.`);
    }

    let contents = configWithGradle.modResults.contents;
    if (contents.includes(MARKER)) return configWithGradle;

    const androidBlock = /(^|\n)android\s*\{/;
    if (!androidBlock.test(contents)) {
      throw new Error(`${MARKER}: android/app/build.gradle has no android { } block.`);
    }

    contents = contents.replace(androidBlock, (match) => `${match}\n${SIGNING_CONFIGS_BLOCK}`);
    contents = useReleaseSigning(contents);
    if (!contents.includes('nilzoraReleaseKeystore ? signingConfigs.release')) {
      throw new Error(
        `${MARKER}: could not point the release build type at the release signing config.`,
      );
    }

    configWithGradle.modResults.contents = `${contents}\n${GUARD_BLOCK}`;
    return configWithGradle;
  });
};

module.exports.MARKER = MARKER;
module.exports.REQUIRED_VARIABLES = REQUIRED_VARIABLES;
