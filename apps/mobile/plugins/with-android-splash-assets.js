/* eslint-disable @typescript-eslint/no-require-imports -- Expo config plugins are loaded by Node from a CommonJS package (no "type": "module" in package.json) */
const { withAppBuildGradle } = require('expo/config-plugins');

/*
 * Packages the supplied launch animation with the Android app.
 *
 * The splash is played by a transparent WebView from
 * `file:///android_asset/nilzora_splash_transparent.webm` (src/startup/splash-timeline.ts), so the
 * file has to sit in the APK's asset root under exactly that name. Nothing copies or re-encodes
 * it: Gradle is told that `apps/mobile/assets/splash-screen` is an extra assets source directory,
 * and the supplied WebM is packaged verbatim.
 *
 * This used to be a hand edit inside android/app/build.gradle, which Expo regenerates on every
 * prebuild — a fresh clone therefore built an app whose animated splash silently fell back to the
 * static native splash. The block below is the same Gradle configuration, applied by prebuild
 * instead, so the repository is the source of truth.
 */

const MARKER = 'nilzora:android-splash-assets';

const SOURCE_SET_BLOCK = `
    // ${MARKER} - see plugins/with-android-splash-assets.js. Generated by Expo prebuild; do not edit.
    //
    // The supplied splash animation ships exactly as supplied, from the APK's asset root, so the
    // launch WebView can load it from file:///android_asset/ without a copy, a re-encode or a
    // base64 payload. The path is relative to android/app, where Gradle evaluates this file.
    sourceSets {
        main {
            assets.srcDirs += file('../../assets/splash-screen')
        }
    }
`;

module.exports = function withAndroidSplashAssets(config) {
  return withAppBuildGradle(config, (configWithGradle) => {
    if (configWithGradle.modResults.language !== 'groovy') {
      throw new Error(
        `${MARKER}: android/app/build.gradle is not Groovy; cannot add the splash assets.`,
      );
    }

    const contents = configWithGradle.modResults.contents;
    if (contents.includes(MARKER)) return configWithGradle;

    // The first `android {` in the generated file is the module's Android block.
    const androidBlock = /(^|\n)android\s*\{/;
    if (!androidBlock.test(contents)) {
      throw new Error(`${MARKER}: android/app/build.gradle has no android { } block.`);
    }

    configWithGradle.modResults.contents = contents.replace(
      androidBlock,
      (match) => `${match}\n${SOURCE_SET_BLOCK}`,
    );
    return configWithGradle;
  });
};
