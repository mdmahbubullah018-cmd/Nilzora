/* eslint-disable @typescript-eslint/no-require-imports -- Expo config plugins are loaded by Node from a CommonJS package (no "type": "module" in package.json) */
const fs = require('node:fs');
const path = require('node:path');
const { withSettingsGradle } = require('expo/config-plugins');

/*
 * Repairs the C++ toolchain for Android library modules on Windows.
 *
 * Two problems, both caused by the Android NDK's CMake entry point defaulting to its "legacy"
 * toolchain file (android.toolchain.cmake L45-53, `include(android-legacy.toolchain.cmake)` then
 * `return()`):
 *
 * 1. The standard library. That file pre-creates an empty flags cache entry
 *    (`set(CMAKE_CXX_FLAGS "" CACHE STRING ...)`), so CMake's own `ANDROID_STL=c++_shared` value
 *    (`-stdlib=libc++`) is discarded, and the same early `return()` skips the code that would add
 *    `-lc++_shared` to the link line. Modules then compile without a standard library and fail at
 *    link time with `ld.lld: error: undefined symbol: std::__ndk1::mutex::~mutex()`. Setting the
 *    flags through the same cache entry is safe: that `set(... CACHE)` has no FORCE, and CMake
 *    composes the value into both the compile flags and the link statement's
 *    `LANGUAGE_COMPILE_FLAGS`. The linker flags name `-lc++_shared` explicitly because compiling
 *    with the flag is not enough on its own. Packaging needs nothing extra: the `react-android`
 *    AAR already ships `libc++_shared.so` for all four ABIs, so AGP merges it into the APK.
 *
 * 2. Long paths. React Native's autolinked codegen mirrors source paths inside the app's CMake
 *    tree, which on Windows runs past the 260 character limit. AGP's default CMake 3.22.1 ships
 *    ninja 1.10.2, which creates directories through the ANSI API and fails first with
 *    `ninja: error: mkdir(...): No such file or directory` (moving the build directory shorter
 *    does not help: the mirrored part alone is over 230 characters). A newer ninja handles those
 *    paths, so every module's CMake is pointed at the newest ninja the Android SDK ships (its
 *    newer CMake packages bundle one). NILZORA_NINJA_PATH overrides that choice. The lookup runs
 *    while Gradle runs, not at prebuild, so no machine path is committed to the repository.
 *
 * The argument is added per module at `defaultConfig`, which is the same supported DSL the native
 * modules themselves use for `-DANDROID_STL`.
 *
 * The hook lives in settings.gradle on purpose. AGP registers its own `afterEvaluate` callback
 * while its plugin is applied, and that callback runs the variant creation that copies
 * `externalNativeBuild.cmake` into a merged model. A hook registered from a subproject's
 * `plugins.withId` therefore runs *after* the copy and is ignored. Registering
 * `gradle.beforeProject` from settings.gradle happens before any project is evaluated, so the
 * `afterEvaluate` it installs is registered first and runs before AGP's variant creation - while
 * still running after the module's own script body has assigned its `arguments` list.
 */

const MARKER = 'nilzora:android-cpp-stl';
/** Compile and link flags, each a separate `-D` argument for the module's CMake configure. */
const ARGUMENTS = [
  '-DCMAKE_CXX_FLAGS=-stdlib=libc++',
  '-DCMAKE_SHARED_LINKER_FLAGS=-stdlib=libc++ -lc++_shared',
  '-DCMAKE_MODULE_LINKER_FLAGS=-stdlib=libc++ -lc++_shared',
];

/**
 * The newest ninja the local Android SDK ships, or an empty string when it ships none. Baked
 * into the generated settings.gradle, which is regenerated on every prebuild, so no machine
 * path is ever committed.
 */
function sdkNinjaPath() {
  const sdkRoot =
    process.env.ANDROID_HOME ||
    process.env.ANDROID_SDK_ROOT ||
    (process.env.LOCALAPPDATA ? path.join(process.env.LOCALAPPDATA, 'Android', 'Sdk') : '');
  if (sdkRoot === '') return '';

  const cmakeRoot = path.join(sdkRoot, 'cmake');
  let packages;
  try {
    packages = fs.readdirSync(cmakeRoot);
  } catch {
    return '';
  }

  const binaries = packages
    .filter((name) => /^\d+(\.\d+)*$/.test(name))
    .sort((a, b) => {
      const left = a.split('.').map(Number);
      const right = b.split('.').map(Number);
      for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
        const difference = (right[index] ?? 0) - (left[index] ?? 0);
        if (difference !== 0) return difference;
      }
      return 0;
    })
    .map((name) =>
      path
        .join(cmakeRoot, name, 'bin', process.platform === 'win32' ? 'ninja.exe' : 'ninja')
        // Groovy treats a backslash as an escape, and the path is written into a Groovy string.
        .replace(/\\/g, '/'),
    );

  return binaries.find((binary) => fs.existsSync(binary)) ?? '';
}

const GRADLE_BLOCK = `
// ${MARKER} - see plugins/with-android-cpp-stl.js. Generated by Expo prebuild; do not edit.
gradle.beforeProject { p ->
  p.afterEvaluate {
    // The app module builds RN's autolinked codegen itself, so it needs the same arguments.
    if (p.plugins.hasPlugin('com.android.library') || p.plugins.hasPlugin('com.android.application')) {
      // Looked up through the extension container: a Gradle property such as
      // \`android.cmakeVersion\` makes Groovy's \`p.android\` resolve to that property instead of
      // the Android extension.
      def androidExt = p.extensions.findByName('android')
      if (androidExt != null) {
        def cmake = androidExt.defaultConfig.externalNativeBuild.cmake
        def wanted = [${ARGUMENTS.map((argument) => `'${argument}'`).join(', ')}]
        def ninja = System.getenv('NILZORA_NINJA_PATH') ?: '${sdkNinjaPath()}'
        if (ninja != '' && new File(ninja).isFile()) {
          wanted.add('-DCMAKE_MAKE_PROGRAM=' + ninja)
        }
        wanted.each { arg ->
          def name = arg.substring(0, arg.indexOf('=') + 1)
          if (!cmake.arguments.any { it.startsWith(name) }) {
            cmake.arguments.add(arg)
          }
        }
      }
    }
  }
}
`;

module.exports = function withAndroidCppStl(config) {
  return withSettingsGradle(config, (configWithGradle) => {
    if (configWithGradle.modResults.language !== 'groovy') {
      throw new Error(
        `${MARKER}: android/settings.gradle is not Groovy; cannot add the C++ STL flag.`,
      );
    }

    const contents = configWithGradle.modResults.contents;
    if (!contents.includes(MARKER)) {
      configWithGradle.modResults.contents = contents + GRADLE_BLOCK;
    }
    return configWithGradle;
  });
};
