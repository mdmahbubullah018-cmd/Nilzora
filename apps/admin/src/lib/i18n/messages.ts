/*
 * Bangla phrases
 * --------------
 * The English text is the key. A component writes `t('Save changes')`; in English that returns
 * the key itself, in Bangla the sentence below. Keeping the English string as the key means
 *
 *  - nothing can drift: there is one registry, and `Phrase` is derived from it, so a component
 *    that asks for a phrase that does not exist fails to compile;
 *  - the fallback is safe by construction: an untranslated string is simply not in this map,
 *    and `t()` then shows the English text instead of a key like `product.variant.save`;
 *  - reviewing coverage means reading one file.
 *
 * Conventions
 *  - Natural, professional Bangla as an office in Dhaka would write it. Common loanwords staff
 *    already use (স্টক, SKU, ভ্যারিয়েন্ট) stay; inventing a pure-Bangla word slows the reader.
 *  - `{name}` placeholders are filled by `t('…', { name })`; they are never translated.
 *  - Nothing dynamic (product names, SKUs, customer names, money) is translated: that is
 *    business data, not interface text.
 */

