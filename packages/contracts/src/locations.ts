/** Delivery zones; the delivery charge depends on the zone of the address's district. */
export const DELIVERY_ZONES = ['inside_dhaka', 'outside_dhaka'] as const;
export type DeliveryZone = (typeof DELIVERY_ZONES)[number];

export function isDistrictOf(division: string, district: string): boolean {
  // Own keys only: inherited names such as "constructor" are not divisions.
  if (!Object.hasOwn(BD_DISTRICTS, division)) return false;
  return BD_DISTRICTS[division as BdDivision].includes(district);
}
